SET legacy.code = 'BSBA-MM',
    legacy.name = 'Bachelor of Science in Business Administration, major in Marketing Management',
    legacy.department_id = (SELECT id FROM departments WHERE code = 'CBA')
WHERE legacy.code = 'BSBA'
  AND replacement.id IS NULL;

